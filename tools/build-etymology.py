#!/usr/bin/env python3
"""Build data/etymology.js from vendored Etymoasis word data (CC BY-SA 4.0).

The generated file and the Chinese glosses in tools/etymoasis-meaning-zh.json
are adaptations and must also be shared under CC BY-SA 4.0.
This script does not copy any Etymoasis site code.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "tools" / "vendor" / "etymoasis" / "etymoasis-data.json"
ZH_PATH = ROOT / "tools" / "etymoasis-meaning-zh.json"
OUT = ROOT / "data" / "etymology.js"

ATTRIBUTION = "Etymoasis，数据来自维基词典贡献者，CC BY-SA 4.0"
SOURCE_URL = "https://etymoasis.me/"
LICENSE = "CC BY-SA 4.0"
LICENSE_URL = "https://creativecommons.org/licenses/by-sa/4.0/"


def forms_of(entry):
    out = []
    for f in entry.get("forms") or []:
        if ":" in f:
            spell, nxt = f.split(":", 1)
            out.append([spell, nxt])
        else:
            out.append([f])
    return out


def compact(kind, zh):
    rows = []
    missing = []
    for e in kind:
        meaning = e.get("meaning") or ""
        meaning_zh = zh.get(meaning)
        if meaning and not meaning_zh:
            missing.append(meaning)
        rows.append({
            "id": e["id"],
            "label": e["label"],
            "meaning": meaning,
            "meaningZh": meaning_zh or meaning,
            "lang": e.get("lang") or "",
            "forms": forms_of(e),
        })
    return rows, missing


def example_index(src, kinds):
    """Map a lowercased illustration word to entry ids that list it."""
    idx = {}
    for kind in kinds:
        for e in src[kind]:
            words = list(e.get("examples") or []) + list(e.get("checked") or [])
            for w in words:
                key = w.lower().strip()
                if not key:
                    continue
                bucket = idx.setdefault(key, [])
                if e["id"] not in bucket:
                    bucket.append(e["id"])
    return idx


def main():
    src = json.loads(SRC.read_text(encoding="utf-8"))
    zh = json.loads(ZH_PATH.read_text(encoding="utf-8"))
    prefixes, miss_p = compact(src["prefixes"], zh)
    roots, miss_r = compact(src["roots"], zh)
    suffixes, miss_s = compact(src["suffixes"], zh)
    missing = sorted(set(miss_p + miss_r + miss_s))
    if missing:
        print("missing Chinese glosses:", file=sys.stderr)
        for m in missing:
            print(" ", m, file=sys.stderr)
        sys.exit(1)
    payload = {
        "attribution": ATTRIBUTION,
        "license": LICENSE,
        "licenseUrl": LICENSE_URL,
        "source": SOURCE_URL,
        "prefixes": prefixes,
        "roots": roots,
        "suffixes": suffixes,
        "noSplit": [x["word"].lower() for x in src.get("no-split") or []],
        "examples": example_index(src, ("prefixes", "roots", "suffixes")),
    }
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    text = (
        "/* Built from tools/vendor/etymoasis (Etymoasis, data from Wiktionary contributors).\n"
        " * Licence: CC BY-SA 4.0. See LICENSES/ETYMOASIS-LICENSE.txt and LICENSES/THIRD_PARTY_NOTICES.md.\n"
        " * Regenerated by tools/build-etymology.py. Do not edit by hand.\n"
        " */\n"
        "(function (root) {\n"
        "  root.DOGVERB_ETYMOLOGY = "
        + body
        + ";\n"
        "})(typeof window !== 'undefined' ? window : typeof globalThis !== 'undefined' ? globalThis : this);\n"
    )
    OUT.write_text(text, encoding="utf-8")
    print(
        f"wrote {OUT.relative_to(ROOT)} "
        f"({OUT.stat().st_size} bytes): "
        f"{len(prefixes)} prefixes, {len(roots)} roots, {len(suffixes)} suffixes, "
        f"{len(payload['examples'])} example words, {len(payload['noSplit'])} no-split"
    )


if __name__ == "__main__":
    main()
